  python3 -m venv "$VENV_DIR"
  # shellcheck disable=SC1091
  . "$VENV_DIR/bin/activate"
  python -m pip install --quiet --upgrade pip
  (cd apps/orchestrator && pip install --quiet -e ".[dev]")
